#!/usr/bin/env python3
"""Build out/india_bullion_monitor_predictor.html .

1. Load F1 (inputs/chart_data.json), record SHA-256 + row counts (anchor checksums), cross-check SPEC §2 constants.
2. Generate src/ssot.js: the frozen SSOT_DB (exact copy of F1) and SSOT_META.
3. Extend the F4 SOURCE template (src/template.html): keep its pages/slicers/charts, add nav, global bar,
   new pages (src/pages.html) and styles (src/styles.css); inline d3 + every src part; no network references.
Usage: python3 src/build.py [--audit out/audit_log.json]
"""
import argparse, datetime, hashlib, json, math, os, re, statistics, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, 'src')
F1 = os.path.join(ROOT, '..', 'data', 'research', 'chart_data.json')
TEMPLATE = os.path.join(SRC, 'template.html')
D3 = os.path.join(ROOT, 'vendor', 'd3.min.js')
OUT = os.path.join(ROOT, 'dist', 'index.html')
JS_PARTS = ['engine.js', 'ui_data.js', 'ui_common.js', 'ui_live.js', 'ui_forecast.js', 'ui_matrix.js', 'ui_accuracy.js', 'ui_caveats.js', 'ui_legacy.js']


def js_json(obj):
    return json.dumps(obj, ensure_ascii=False, allow_nan=False, separators=(',', ':')).replace('</', '<\\/')


def constant_checks(d):
    """SPEC §2 constants vs F1 (F1 wins); returns list of strings."""
    out = []
    rows = [r for r in d['decomposition_log_points'] if r['fiscal_year'] >= '1990-91']
    def chk(name, spec, val, tol):
        ok = abs(spec - val) <= tol
        out.append(f"{name}: SPEC {spec} vs F1 {round(val, 4)} {'OK' if ok else 'MISMATCH (F1 wins)'}")
    chk('post-1990 rows', 36, len(rows), 0)
    for p, sp in (('g', (10.0, 6.5, 4.6, -1.1, 12.3, 13.6, 7.6, 4.4)), ('s', (8.8, 6.4, 4.7, -2.3, 17.7, 20.0, 7.6, 7.3))):
        keys = [p + '_total', p + '_world', p + '_fx', p + '_prem']
        for k, s in zip(keys, sp[:4]):
            chk(f'mean {k}', s, statistics.mean(r[k] for r in rows), 0.051)
        for k, s in zip(keys, sp[4:]):
            chk(f'SD {k}', s, statistics.stdev(r[k] for r in rows), 0.051)
    st = {(r['metal'], r['start']): r for r in d['duty_vs_premium_stats']}
    chk('gold duty slope', 0.98, st[('Gold', '2000-01')]['slope'], 0.0051)
    chk('silver duty slope', 0.83, st[('Silver', '2000-01')]['slope'], 0.0051)
    chk('gold duty intercept', 0.56, st[('Gold', '2000-01')]['intercept'], 0.0051)
    chk('silver duty intercept', 3.10, st[('Silver', '2000-01')]['intercept'], 0.0051)
    my = {r['fiscal_year']: r for r in d['master_yearly']}
    chk('FY2025-26 gold', 118420.90, my['2025-26']['gold_rs_per_10g'], 0.001)
    chk('FY2025-26 silver', 162672.25, my['2025-26']['silver_rs_per_kg'], 0.001)
    chk('FY2026-27 YTD gold', 149723.66, my['2026-27']['gold_rs_per_10g'], 0.001)
    chk('FY2026-27 YTD silver', 239733.63, my['2026-27']['silver_rs_per_kg'], 0.001)
    chk('INR/USD 2026-27 (DERIVED)', 94.71, my['2026-27']['inr_per_usd'], 0.001)
    chk('Apr 2026 gold premium %', 5.61, my['2026-27']['gold_premium_pct_DERIVED'], 0.001)
    chk('Apr 2026 silver premium %', 6.03, my['2026-27']['silver_premium_pct_DERIVED'], 0.001)
    mo = {r['month']: r for r in d['monthly_2025_2026']}
    chk('Aug 2026 gold', 153234, mo['2026-08']['gold_rs_10g'], 0.001)
    chk('Aug 2026 silver', 229655, mo['2026-08']['silver_rs_kg'], 0.001)
    out.append("Duty slope default uses SPEC two-decimal values 0.98 / 0.83 (F1 0.981 / 0.825 round to them); the walk-forward backtest re-fits the slope on data up to each origin.")
    return out


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--audit', help='path to audit_log.json to embed'); ap.add_argument('--out', default=OUT); a = ap.parse_args()
    os.makedirs(os.path.dirname(os.path.abspath(a.out)), exist_ok=True)
    raw = open(F1, 'rb').read(); sha = hashlib.sha256(raw).hexdigest(); d = json.loads(raw)
    counts = {k: len(v) for k, v in d.items() if isinstance(v, list)}
    sp = os.path.join(ROOT, 'docs', 'STATE.json'); state = json.load(open(sp)) if os.path.exists(sp) else {}
    rec = (state.get('input_sha256') or {}).get('F1')
    sha_note = ('recorded at build (no STATE file)' if rec is None else ('matches STATE.input_sha256.F1' if rec == sha else f'DIFFERS from STATE.input_sha256.F1 ({rec})'))
    print('F1 sha256', sha, sha_note); print('row counts', counts)
    meta = {'f1_path': 'data/chart_data.json', 'f1_sha256': sha, 'f1_sha256_state_check': sha_note, 'row_counts': counts,
            'built_utc': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'), 'mismatches': constant_checks(d),
            'annual_series_rule': "rows whose gold_value_type/silver_value_type starts with 'RBI FY'"}
    for m in meta['mismatches']:
        if 'MISMATCH' in m: print('  ', m)
    ssot_js = ("/* GENERATED by src/build.py from inputs/chart_data.json (F1). Do not edit. SSOT_DB is an exact, deep-frozen copy of F1. */\n"
               "(function(root){'use strict';function deepFreeze(o){if(o&&typeof o==='object'&&!Object.isFrozen(o)){Object.getOwnPropertyNames(o).forEach(function(k){deepFreeze(o[k]);});Object.freeze(o);}return o;}\n"
               f"root.SSOT_DB=deepFreeze({js_json(d)});\nroot.SSOT_META=deepFreeze({js_json(meta)});\n"
               "})(typeof window!=='undefined'?window:globalThis);\n")
    open(os.path.join(SRC, 'ssot.js'), 'w').write(ssot_js)
    audit_obj = None
    if a.audit:
        audit_obj = json.load(open(a.audit)); print('embedding audit', a.audit, audit_obj.get('status'))

    t = open(TEMPLATE).read()
    def rep(old, new, count=1):
        nonlocal t
        assert t.count(old) == count, (old[:60], t.count(old)); t = t.replace(old, new)
    parts = open(os.path.join(SRC, 'pages.html')).read()
    sect = lambda name: parts.split(f'<!--{name}-->')[1].split(f'<!--/{name}-->')[0]
    rep('<title>Gold &amp; Silver in India 1946–2026 · Executive Dashboard</title>',
        f'<title>India Bullion Monitor &amp; Predictor · gold &amp; silver, SSOT 1946–2026</title>\n<meta name="ssot-f1-sha256" content="{sha}">\n'
        '<meta http-equiv="Content-Security-Policy" content="default-src \'none\'; script-src \'unsafe-inline\'; style-src \'unsafe-inline\'; img-src data: blob:; connect-src \'none\'; font-src \'none\'; frame-src \'none\'; object-src \'none\'; base-uri \'none\'; form-action \'none\'">')
    rep('</style>', '</style>\n<style>\n' + open(os.path.join(SRC, 'styles.css')).read() + '</style>')
    rep('<h1>Gold &amp; Silver in India<br>1946–2026</h1>', '<h1>India Bullion Monitor &amp; Predictor</h1>')
    rep('<div class="sub">Executive dashboard · Indian government sources (RBI, Lok Sabha, Ministry of Finance)</div>',
        '<div class="sub">Live nowcast, 1W/1M/1Y ranges and measured accuracy · SSOT: Indian government sources (RBI, Lok Sabha, Ministry of Finance)</div>' + sect('NAV'))
    rep('<button data-page="overview" class="on">Overview</button>', '<button data-page="overview">Overview</button>')
    rep('<main>\n', '<main>\n' + sect('GBAR'))
    rep('  <div class="foot">', sect('PAGES') + '  <div class="foot">')
    rep('Grams of silver that buy one gram of gold in Mumbai', 'Grams of silver equal in value to one gram of gold in Mumbai')
    rep('Built 21 Nov 2026 from Indian government sources.', 'SSOT built from F1 (sha256 ' + sha[:12] + '…) · Indian government sources; live data only via loaded JSON files (quarantined).')
    # scripts
    i0 = t.index('<script>__D3__</script>'); i1 = t.index('</script>', t.index('<script>\n(function(){')) + len('</script>')
    d3 = open(D3).read()
    scripts = ['<script>' + d3 + '</script>', '<script>' + ssot_js + '</script>',
               '<script>window.AUDIT_LOG=' + (js_json(audit_obj) if audit_obj is not None else 'null') + ';</script>']
    for p in JS_PARTS:
        s = open(os.path.join(SRC, p)).read()
        assert '</script' not in s.lower(), p
        scripts.append(f'<script>/* src/{p} */\n{s}\n</script>')
    scripts.append('<script>window.UI.init();</script>')
    t = t[:i0] + '\n'.join(scripts) + t[i1:]
    assert '__D3__' not in t and '__DATA__' not in t
    # offline guard: no http(s) in src=/href= except user-facing <a href> links built at runtime
    bad = re.findall(r'(?:src|href)\s*=\s*["\']https?:', t)
    assert not bad, bad
    open(a.out, 'w').write(t)
    print('wrote', a.out, len(t.encode()), 'bytes')
    return 0


if __name__ == '__main__':
    sys.exit(main())
